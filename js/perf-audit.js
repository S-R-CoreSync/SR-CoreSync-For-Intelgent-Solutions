// perf-audit.js – Web Performance & Speed Audit Studio
// Uses the minimal stub `window.webVitals` defined in web-vitals.min.js.
// Draws circular gauges on canvas for LCP, FID, CLS, TTFB and provides an export to PDF.

// Helper: draw a circular gauge on a given canvas context
function drawGauge(ctx, value, max, label) {
  const size = ctx.canvas.width; // assume square canvas
  const radius = size / 2 - 5;
  const center = size / 2;
  ctx.clearRect(0, 0, size, size);

  // Background circle (light gray)
  ctx.beginPath();
  ctx.arc(center, center, radius, 0, 2 * Math.PI);
  ctx.strokeStyle = '#e5e7eb';
  ctx.lineWidth = 8;
  ctx.stroke();

  // Determine color based on performance thresholds (green/yellow/red)
  let color = '#10b981'; // good (green)
  if (label === 'LCP') {
    if (value > 4) color = '#ef4444'; // poor
    else if (value > 2.5) color = '#f59e0b'; // moderate
  } else if (label === 'FID') {
    if (value > 300) color = '#ef4444';
    else if (value > 100) color = '#f59e0b';
  } else if (label === 'CLS') {
    if (value > 0.25) color = '#ef4444';
    else if (value > 0.1) color = '#f59e0b';
  } else if (label === 'TTFB') {
    if (value > 0.8) color = '#ef4444';
    else if (value > 0.4) color = '#f59e0b';
  }

  // Foreground arc (value proportion)
  const proportion = Math.min(value / max, 1);
  const endAngle = -0.5 * Math.PI + proportion * 2 * Math.PI;
  ctx.beginPath();
  ctx.arc(center, center, radius, -0.5 * Math.PI, endAngle);
  ctx.strokeStyle = color;
  ctx.lineWidth = 8;
  ctx.stroke();

  // Value text
  ctx.fillStyle = '#111827';
  ctx.font = 'bold 14px sans-serif';
  ctx.textAlign = 'center';
  ctx.textBaseline = 'middle';
  const display = label === 'CLS' ? value.toFixed(3) : value.toString();
  ctx.fillText(display, center, center);

  // Label under the gauge
  ctx.font = '12px sans-serif';
  ctx.fillText(label, center, size - 15);
}

// Gather metrics and render gauges
function runAudit() {
  const metrics = {};
  const ready = Promise.all([
    new Promise((res) => webVitals.getLCP((data) => { metrics.LCP = data.value; res(); })),
    new Promise((res) => webVitals.getFID((data) => { metrics.FID = data.value; res(); })),
    new Promise((res) => webVitals.getCLS((data) => { metrics.CLS = data.value; res(); })),
    new Promise((res) => webVitals.getTTFB((data) => { metrics.TTFB = data.value; res(); })),
  ]);

  ready.then(() => {
    // Draw each gauge
    drawGauge(document.querySelector('#lcpMetric canvas').getContext('2d'), metrics.LCP, 5, 'LCP');
    drawGauge(document.querySelector('#fidMetric canvas').getContext('2d'), metrics.FID, 300, 'FID');
    drawGauge(document.querySelector('#clsMetric canvas').getContext('2d'), metrics.CLS, 0.25, 'CLS');
    drawGauge(document.querySelector('#ttfbMetric canvas').getContext('2d'), metrics.TTFB, 0.8, 'TTFB');

    // Store for later export
    window._auditMetrics = metrics;
  });
}

// Export report as PDF – clone metrics section into a printable container
function exportPDF() {
  const clone = document.createElement('div');
  clone.style.position = 'fixed';
  clone.style.top = '0';
  clone.style.left = '0';
  clone.style.width = '100%';
  clone.style.height = '100%';
  clone.style.background = '#fff';
  clone.style.zIndex = '9999';
  clone.style.overflow = 'auto';
  clone.innerHTML = `
    <h1 style="text-align:center;margin:20px 0;">تقرير فحص الأداء</h1>
    <div style="display:flex;flex-wrap:wrap;justify-content:center;gap:20px;">
      ${document.getElementById('metricsSection').innerHTML}
    </div>
    <p style="text-align:center;margin-top:20px;">Generated by S&R CoreSync – ${new Date().toLocaleString('ar-EG')}</p>
  `;
  document.body.appendChild(clone);
  setTimeout(() => { window.print(); document.body.removeChild(clone); }, 500);
}

document.addEventListener('DOMContentLoaded', () => {
  runAudit();
  document.getElementById('exportReportBtn').addEventListener('click', exportPDF);
});
