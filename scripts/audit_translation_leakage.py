"""
Translation leakage audit
=========================

The multilingual portals are generated by replacing English source strings with
localized ones. When a string is missing from a language's dictionary the
replacement silently does nothing and the English sentence ships inside a Maltese
or Norwegian page. Arabic can leak the same way, and also through attributes.

This tool measures the leak instead of asserting that it is absent:

  * English leak - a text block of 4+ words that is byte-identical to a block in
    the English master. Since every portal is generated *from* that master, an
    identical block is by definition untranslated.
  * Arabic leak  - an Arabic-script run inside a page whose language is neither
    Arabic nor Kurdish.

It reports per language, and exits non-zero when a page exceeds the allowance, so
it can be wired into CI as a gate that a regression cannot silently pass.

Usage:
    python scripts/audit_translation_leakage.py
    python scripts/audit_translation_leakage.py --lang mt no
    python scripts/audit_translation_leakage.py --json report.json
"""
import argparse
import html
import json
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))

LANGUAGES = [
    'en', 'nl', 'de', 'tr', 'ckb', 'ku', 'bg', 'cs', 'da', 'el', 'es', 'et',
    'fi', 'fr', 'ga', 'hr', 'hu', 'it', 'lt', 'lv', 'mt', 'no', 'pl', 'pt',
    'ro', 'sk', 'sl', 'sv',
]

# Scripts where Arabic letters are the native script, not a leak.
ARABIC_SCRIPT_LANGS = {'ar', 'ckb', 'ku'}

STRIP_BLOCKS = re.compile(r'(?is)<(script|style|noscript|template)\b.*?</\1>')
COMMENT = re.compile(r'(?s)<!--.*?-->')
TAG = re.compile(r'(?s)<[^>]+>')
ATTR_TEXT = re.compile(r'(?is)\b(?:alt|title|aria-label|placeholder|content)\s*=\s*"([^"]{4,})"')

ARABIC_RUN = re.compile(r'[\u0600-\u06FF\u0750-\u077F\u08A0-\u08FF]{2,}(?:[ \u0600-\u06FF]{0,40})')
LATIN_BLOCK = re.compile(r'^[A-Za-z0-9 ,.;:!?%()\-\'"&/+=*_#@\[\]{}|~$^<>]{20,}$')

# Text that is legitimately identical across languages: brand, product, legal and
# technical names. Kept deliberately short - anything added here is a place where
# leakage can hide.
ALLOWED_IDENTICAL = {
    'S&R CoreSync', 'CoreSync', 'S&R', 'S&R CoreSync Solutions',
    'S&R CoreSync For Intelligent Solutions', 'GDPR', 'EU GDPR', 'BTW', 'VAT',
    'ERP', 'SaaS', 'API', 'SDK', 'PWA', 'AI', 'SEO', 'SLA', 'KPI', 'ROI',
    'Next.js', 'React', 'Node.js', 'Python', 'Stripe', 'Mollie', 'AWS',
    'Google Cloud', 'Vercel Edge', 'Cloudflare', 'iDEAL', 'SEPA', 'WhatsApp',
    'LinkedIn', 'Instagram', 'Facebook', 'TikTok', 'Telegram', 'YouTube',
    'Snapchat', 'Belastingdienst', 'EU 2016/679', 'AMS-IX', 'ISO 27001',
    'Mohammad Salim Aziza', 'Mohammad Raed Kaaka', 'Salim Aziza', 'Raed Kaaka',
}


def visible_blocks(path):
    """Return (text blocks of 4+ words, attribute strings) with HTML removed."""
    with open(path, 'r', encoding='utf-8', errors='ignore') as fh:
        raw = fh.read()
    attrs = {html.unescape(a).strip() for a in ATTR_TEXT.findall(raw)}
    raw = STRIP_BLOCKS.sub(' ', raw)
    raw = COMMENT.sub(' ', raw)
    raw = TAG.sub('\n', raw)
    raw = html.unescape(raw)
    blocks = []
    for chunk in re.split(r'[\n\r]+', raw):
        text = ' '.join(chunk.split())
        if len(text.split()) >= 4:
            blocks.append(text)
    return blocks, attrs


def arabic_runs(blocks, attrs):
    hits = []
    for text in list(blocks) + list(attrs):
        for match in ARABIC_RUN.finditer(text):
            hits.append(match.group(0).strip())
    return hits


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--lang', nargs='*', default=None)
    ap.add_argument('--json', default=None)
    ap.add_argument('--allow-english', type=int, default=0,
                    help='permitted untranslated English blocks before failing')
    args = ap.parse_args()

    en_path = os.path.join(ROOT, 'en', 'index.html')
    en_blocks, _ = visible_blocks(en_path)
    en_set = set(en_blocks)

    langs = args.lang or [l for l in LANGUAGES if l != 'en']
    report = {}
    failures = []

    print('=' * 92)
    print('%-4s %8s %10s %10s %10s' % ('lang', 'blocks', 'EN leak', 'AR runs', 'EN leak %'))
    print('=' * 92)

    for lang in langs:
        path = os.path.join(ROOT, lang, 'index.html')
        if not os.path.exists(path):
            print('%-4s  MISSING' % lang)
            continue
        blocks, attrs = visible_blocks(path)
        en_leak = [b for b in blocks if b in en_set and b not in ALLOWED_IDENTICAL]
        ar = [] if lang in ARABIC_SCRIPT_LANGS else arabic_runs(blocks, attrs)
        pct = 100.0 * len(en_leak) / len(blocks) if blocks else 0.0
        report[lang] = {
            'blocks': len(blocks),
            'english_leak': en_leak,
            'arabic_runs': ar,
        }
        flag = ''
        if en_leak or ar:
            flag = '  <-- LEAK'
            failures.append(lang)
        print('%-4s %8d %10d %10d %9.1f%%%s' % (lang, len(blocks), len(en_leak), len(ar), pct, flag))

    print('=' * 92)
    print('languages with leakage: %d of %d' % (len(failures), len(langs)))
    print('(EN leak = a visible block identical to the English master, i.e. never translated)')

    if args.json:
        with open(args.json, 'w', encoding='utf-8') as fh:
            json.dump(report, fh, indent=2, ensure_ascii=False)
        print('detail written to %s' % args.json)

    worst = sorted(report.items(), key=lambda kv: -len(kv[1]['english_leak']))[:3]
    for lang, data in worst:
        if not data['english_leak']:
            continue
        print('\n-- %s: first untranslated blocks --' % lang)
        for block in data['english_leak'][:5]:
            print('   %s' % block[:110])
        if data['arabic_runs']:
            print('   [arabic] %s' % ' | '.join(data['arabic_runs'][:4]))

    over = [l for l in langs
            if len(report.get(l, {}).get('english_leak', [])) > args.allow_english]
    return 1 if over else 0


if __name__ == '__main__':
    sys.exit(main())
