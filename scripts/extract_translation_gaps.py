"""
Extract the exact translation gap, per language
===============================================

The portals are generated by replacing English strings. Any string missing from
the generator's dictionary is left in English and ships silently. This tool turns
that invisible debt into an enumerable work list:

    i18n/gaps/<lang>.json   everything that language still shows in English
    i18n/gaps/_summary.json totals, plus the strings leaking into most languages

Ordering is by how many languages leak the same string, so translating the top of
the list fixes the most pages per unit of work.

Blocks made mostly of proper nouns, product names and units are filtered out -
they are legitimately identical in every language and translating them would be
wrong (a Maltese page should still say "Odoo").

Usage:
    python scripts/extract_translation_gaps.py
    python scripts/extract_translation_gaps.py --lang mt no
"""
import argparse
import collections
import html
import io
import json
import os
import re
import sys

if hasattr(sys.stdout, 'reconfigure'):
    sys.stdout.reconfigure(encoding='utf-8')

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT_DIR = os.path.join(ROOT, 'scripts', 'i18n', 'gaps')

LANGUAGES = [
    'en', 'nl', 'de', 'tr', 'ckb', 'ku', 'bg', 'cs', 'da', 'el', 'es', 'et',
    'fi', 'fr', 'ga', 'hr', 'hu', 'it', 'lt', 'lv', 'mt', 'no', 'pl', 'pt',
    'ro', 'sk', 'sl', 'sv',
]

STRIP_BLOCKS = re.compile(r'(?is)<(script|style|noscript|template)\b.*?</\1>')
COMMENT = re.compile(r'(?s)<!--.*?-->')
TAG = re.compile(r'(?s)<[^>]+>')

# Tokens that legitimately stay identical across languages.
NEUTRAL = {
    'S&R', 'CoreSync', 'Solutions', 'For', 'Intelligent', 'ERP', 'AI', 'LLM',
    'CTO', 'CFO', 'CEO', 'Odoo', 'Cloud', 'GDPR', 'EU', 'BTW', 'VAT', 'API',
    'SaaS', 'SDK', 'PWA', 'SEO', 'KPI', 'ROI', 'SLA', 'NFC', 'PDF', 'QR',
    'Next.js', 'React', 'Node.js', 'Python', 'Stripe', 'Mollie', 'AWS',
    'Google', 'Vercel', 'Edge', 'Cloudflare', 'iDEAL', 'SEPA', 'WhatsApp',
    'LinkedIn', 'Instagram', 'Facebook', 'TikTok', 'Telegram', 'YouTube',
    'Snapchat', 'Belastingdienst', 'AMS-IX', 'ISO', 'IFRS', 'Mohammad',
    'Salim', 'Aziza', 'Raed', 'Kaaka', 'Mr.', 'Eng.', '&', '|', '•', '+', '%',
}


def visible_blocks(path):
    with io.open(path, 'r', encoding='utf-8', errors='ignore') as fh:
        raw = fh.read()
    raw = STRIP_BLOCKS.sub(' ', raw)
    raw = COMMENT.sub(' ', raw)
    raw = TAG.sub('\n', raw)
    raw = html.unescape(raw)
    out = []
    for chunk in re.split(r'[\n\r]+', raw):
        text = ' '.join(chunk.split())
        if len(text.split()) >= 4:
            out.append(text)
    return out


def is_neutral(text):
    tokens = [t for t in re.split(r'\s+', text) if t]
    if not tokens:
        return True
    known = 0
    for token in tokens:
        bare = token.strip('.,()[]{}|•—-:;!?"\'')
        if bare in NEUTRAL or re.fullmatch(r'[0-9+%.,/&×\-]+', bare):
            known += 1
    return known / len(tokens) >= 0.6


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--lang', nargs='*', default=None)
    args = ap.parse_args()

    en_blocks = visible_blocks(os.path.join(ROOT, 'en', 'index.html'))
    en_set = set(en_blocks)
    langs = [l for l in (args.lang or LANGUAGES) if l != 'en']

    leak_by_lang = {}
    frequency = collections.Counter()

    for lang in langs:
        path = os.path.join(ROOT, lang, 'index.html')
        if not os.path.exists(path):
            continue
        blocks = visible_blocks(path)
        leak = sorted({b for b in blocks if b in en_set and not is_neutral(b)})
        leak_by_lang[lang] = leak
        for block in leak:
            frequency[block] += 1

    os.makedirs(OUT_DIR, exist_ok=True)
    for lang, leak in leak_by_lang.items():
        with io.open(os.path.join(OUT_DIR, lang + '.json'), 'w', encoding='utf-8') as fh:
            json.dump({'language': lang, 'source': 'en/index.html',
                       'count': len(leak), 'strings': leak}, fh, indent=2, ensure_ascii=False)

    total_unique = len(frequency)
    summary = {
        'languages': len(leak_by_lang),
        'unique_untranslated_strings': total_unique,
        'per_language': {k: len(v) for k, v in sorted(leak_by_lang.items(), key=lambda kv: -len(kv[1]))},
        'most_widespread': [{'string': s, 'languages': c} for s, c in frequency.most_common(40)],
    }
    with io.open(os.path.join(OUT_DIR, '_summary.json'), 'w', encoding='utf-8') as fh:
        json.dump(summary, fh, indent=2, ensure_ascii=False)

    print('=' * 80)
    print('translation gap: %d unique English strings across %d languages'
          % (total_unique, len(leak_by_lang)))
    print('=' * 80)
    for lang, leak in sorted(leak_by_lang.items(), key=lambda kv: -len(kv[1])):
        print('  %-4s %4d untranslated strings' % (lang, len(leak)))
    print('\nwritten: i18n/gaps/<lang>.json + _summary.json')
    print('\n-- strings leaking into the most languages --')
    for s, c in frequency.most_common(12):
        print('  %2d langs | %s' % (c, s[:86]))
    return 0


if __name__ == '__main__':
    sys.exit(main())
